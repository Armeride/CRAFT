import '@fontsource-variable/noto-sans-kr';
import '@fontsource-variable/inter';
import {readPreferences,applyPreferences} from './preferences.js';
import { createRoot } from 'react-dom/client';
import { setupI18n, initialLocale } from './i18n.js';
import { stored } from './api.js';
import { App } from './App.js';
import './styles.css';
const preferences=readPreferences(initialLocale(stored('craft.locale'), navigator.languages));
applyPreferences(preferences);
await setupI18n(preferences.locale);
createRoot(document.getElementById('root')!).render(<App initialPreferences={preferences}/>);
